package cli

import (
	"os"
	"path/filepath"
	"strings"
)

const artifactIgnoreLine = ".beacon/artifacts/"

// ensureArtifactsIgnored makes the derived HTML tree untracked by default.
// The root .gitignore is the reliable layer (the nested .gitignore alone
// would still show as an untracked directory before it is committed).
func ensureArtifactsIgnored(projRoot string) error {
	ignorePath := filepath.Join(projRoot, ".gitignore")
	raw, err := os.ReadFile(ignorePath)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	text := string(raw)
	if !hasIgnoreLine(text, artifactIgnoreLine) {
		if text != "" && !strings.HasSuffix(text, "\n") {
			text += "\n"
		}
		text += "\n# generated by beacon: derived renders are not truth\n" + artifactIgnoreLine + "\n"
		if err := os.WriteFile(ignorePath, []byte(text), 0o644); err != nil {
			return err
		}
	}
	nested := filepath.Join(projRoot, ".beacon", "artifacts", ".gitignore")
	if err := os.MkdirAll(filepath.Dir(nested), 0o755); err != nil {
		return err
	}
	return os.WriteFile(nested, []byte("*\n!.gitignore\n"), 0o644)
}

func hasIgnoreLine(text, want string) bool {
	for _, line := range strings.Split(text, "\n") {
		switch strings.TrimSpace(line) {
		case want, strings.TrimSuffix(want, "/"), "/" + want:
			return true
		}
	}
	return false
}

func isInside(root, p string) bool {
	rel, err := filepath.Rel(root, p)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}
